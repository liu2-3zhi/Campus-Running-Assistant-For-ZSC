"""Finance tables for the v4 business schema."""
from sqlalchemy import (
    BigInteger, Boolean, CheckConstraint, Column, DateTime, ForeignKey, Index,
    Integer, JSON, String, Table, Text, UniqueConstraint,
)


def add_finance_tables(metadata, *, id_type, identifier, table_options):
    Table(
        "payment_orders", metadata,
        Column("id", id_type, primary_key=True, autoincrement=True),
        Column("order_id", identifier(128), nullable=False),
        Column("system_account_id", id_type, ForeignKey("system_accounts.id", ondelete="SET NULL")),
        Column("auth_username", identifier(200)),
        Column("username", identifier(200)),
        Column("amount_minor", BigInteger, nullable=False),
        Column("refund_total_minor", BigInteger),
        Column("status", String(32), nullable=False),
        Column("pay_type", String(32)),
        Column("payment_method", String(32)),
        Column("payment_type", String(32)),
        Column("trade_no", identifier(128)),
        Column("api_trade_no", identifier(128)),
        Column("product_name", Text),
        Column("total_count", Integer),
        Column("created_at", DateTime),
        Column("paid_at", DateTime),
        Column("expires_at", DateTime),
        Column("closed_at", DateTime),
        Column("active_query_token_hash", identifier(64)),
        Column("active_query_session_hash", identifier(64)),
        Column("active_query_token_expires_at", DateTime),
        Column("active_query_token_used", Boolean),
        Column("provider_data", JSON),
        UniqueConstraint("order_id", name="uq_payment_orders_order_id"),
        CheckConstraint("amount_minor >= 0", name="ck_payment_orders_amount"),
        CheckConstraint("refund_total_minor >= 0", name="ck_payment_orders_refund_total"),
        Index("ix_payment_orders_system_account_created", "system_account_id", "created_at"),
        Index("ix_payment_orders_auth_username_created", "auth_username", "created_at"),
        Index("ix_payment_orders_username_created", "username", "created_at"),
        Index("ix_payment_orders_status_expires", "status", "expires_at"),
        Index("ix_payment_orders_trade_no", "trade_no"),
        Index("ix_payment_orders_api_trade_no", "api_trade_no"),
        **table_options,
    )

    Table(
        "billing_records", metadata,
        Column("id", id_type, primary_key=True, autoincrement=True),
        Column("school_account_id", id_type, ForeignKey("school_accounts.id"), nullable=False),
        Column("billing_id", identifier(128), nullable=False),
        Column("system_account_id", id_type, ForeignKey("system_accounts.id", ondelete="SET NULL")),
        Column("auth_username", identifier(200)),
        Column("amount_minor", BigInteger, nullable=False),
        Column("reason", Text),
        Column("status", String(32), nullable=False),
        Column("created_at", DateTime),
        Column("updated_at", DateTime),
        Column("paid_at", DateTime),
        Column("paid_by", identifier(200)),
        Column("final_payment_order_id", id_type, ForeignKey("payment_orders.id")),
        Column("admin_cleared_at", DateTime),
        Column("admin_cleared_by", identifier(200)),
        UniqueConstraint("school_account_id", "billing_id", name="uq_billing_records_school_bill"),
        CheckConstraint("amount_minor >= 0", name="ck_billing_records_amount"),
        Index("ix_billing_records_billing_id", "billing_id"),
        Index("ix_billing_records_school_status_created", "school_account_id", "status", "created_at"),
        Index("ix_billing_records_system_account", "system_account_id"),
        Index("ix_billing_records_final_order", "final_payment_order_id"),
        **table_options,
    )

    Table(
        "payment_order_bills", metadata,
        Column("payment_order_id", id_type, ForeignKey("payment_orders.id"), primary_key=True),
        Column("billing_record_id", id_type, ForeignKey("billing_records.id"), primary_key=True),
        Column("position", Integer),
        Column("amount_minor", BigInteger),
        Column("quantity", Integer),
        CheckConstraint("position >= 0", name="ck_payment_order_bills_position"),
        CheckConstraint("amount_minor >= 0", name="ck_payment_order_bills_amount"),
        CheckConstraint("quantity > 0", name="ck_payment_order_bills_quantity"),
        Index("ix_payment_order_bills_billing_record", "billing_record_id"),
        **table_options,
    )

    Table(
        "payment_refunds", metadata,
        Column("id", id_type, primary_key=True, autoincrement=True),
        Column("payment_order_id", id_type, ForeignKey("payment_orders.id"), nullable=False),
        Column("sequence", Integer, nullable=False),
        Column("refund_id", identifier(128)),
        Column("out_refund_no", identifier(128)),
        Column("refund_no", identifier(128)),
        Column("out_request_no", identifier(128)),
        Column("refund_trade_no", identifier(128)),
        Column("amount_minor", BigInteger, nullable=False),
        Column("reason", Text),
        Column("refund_time", DateTime),
        Column("created_at", DateTime),
        Column("operator", identifier(200)),
        Column("status", String(32)),
        Column("provider_data", JSON),
        UniqueConstraint("payment_order_id", "sequence", name="uq_payment_refunds_order_sequence"),
        CheckConstraint("sequence >= 0", name="ck_payment_refunds_sequence"),
        CheckConstraint("amount_minor > 0", name="ck_payment_refunds_amount"),
        Index("ix_payment_refunds_out_refund_no", "out_refund_no"),
        Index("ix_payment_refunds_refund_no", "refund_no"),
        **table_options,
    )
